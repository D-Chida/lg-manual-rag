import os
from pathlib import Path
from docx import Document


def create_document_1(output_path: Path):
    doc = Document()
    doc.add_heading("水道料金事務マニュアル：漏水減免・更正処理編", level=0)

    # 第1章
    doc.add_heading("第1章 漏水減免の適用基準", level=1)

    doc.add_heading("1.1 減免対象となる不可抗力な地下漏水の判定基準", level=2)
    doc.add_paragraph(
        "地下埋設給水管、壁体内配管、床下配管など、利用者が善良な管理者としての注意をもってしても"
        "通常発見することが困難な不可抗力による漏水を減免対象とする。"
        "漏水箇所の修繕は、市水道局が指定した「指定給水装置工事事業者」によって適正に完了していることを必須条件とする。"
    )

    doc.add_heading("1.2 減免対象外の基準", level=2)
    doc.add_paragraph(
        "以下の事由による漏水・水量増は減免の対象外とし、全額を利用者の負担とする。\n"
        "・蛇口、給水栓の閉め忘れや不完全な閉鎖\n"
        "・水洗トイレのボールタップ不良、ロータンク内の不具合による連続流水（容易に発見可能とみなす）\n"
        "・受水槽、高置水槽、給湯器、温水器等の給水器具本体およびその接続部からの漏水\n"
        "・露出配管の破損で、外観から容易に認知可能であったもの\n"
        "・過去に検針員や局職員から漏水の指摘・修繕勧告を受けながら、正当な理由なく1か月以上放置していた場合"
    )

    doc.add_heading("1.3 減免水量の算定式", level=2)
    doc.add_paragraph(
        "漏水減免における認定水量および減免水量の算定は、以下の基準式に従って厳格に行う。\n\n"
        "【算定式】\n"
        "1. 基準水量（通常使用水量） ＝ 直近前年同期の使用水量（前年同期の実績がない場合は、漏水前3回の検針平均水量）\n"
        "2. 漏水推定水量 ＝ 当期検針水量 － 基準水量\n"
        "3. 減免認定水量 ＝ 漏水推定水量 × 減免率（原則50%）\n"
        "4. 更正後請求水量 ＝ 当期検針水量 － 減免認定水量\n\n"
        "※なお、下水道使用料については、公共下水道に流入していないことが確認された地下漏水に限り、漏水推定水量の全量（100%）を減免対象として認定する。"
    )

    # 第2章
    doc.add_heading("第2章 端末操作手順", level=1)

    doc.add_heading("2.1 システムメニュー「料金更正管理」からの入力フロー", level=2)
    doc.add_paragraph(
        "1. 上下水道料金総合基幹システムにログイン後、トップメニューより「業務処理」→「収納・更正業務」→「料金更正管理」を選択する。\n"
        "2. 検索画面にて対象者の「調定番号」または「水栓番号（お客様番号）」を入力し、「検索」ボタンを押下する。\n"
        "3. 該当の調定レコードを選択し、画面下部の「更正処理開始」をクリックする。\n"
        "4. 処理区分コンボボックスより「減額更正」を選択し、更正対象となる「調定年月」を指定する。"
    )

    doc.add_heading("2.2 更正事由コード「K-12」の選択と再計算", level=2)
    doc.add_paragraph(
        "1. 更正事由コード入力欄に「K-12」（コード名称：給水管地下漏水に伴う減免更正）を選択・入力する。\n"
        "2. 「算定水量算出」ボタンをクリックし、算定基準となる前年同期実績を自動取得する。\n"
        "3. 減免率「50%」が正しく適用され、水道料金および下水道使用料の更正後金額が正確に再計算されていることを画面プレビューで確認する。\n"
        "4. 確認後、「一時保存」または「承認伺い発行」を実行する。"
    )

    doc.add_heading("2.3 必要書類の確認とシステム添付", level=2)
    doc.add_paragraph(
        "更正処理を本登録・決裁回付する前に、以下の申請書類一式が提出されているか確認し、電子ファイリング機能へ登録する。\n"
        "・様式第4号「水道料金・下水道使用料減免申請書」（使用者本人の署名・捺印）\n"
        "・指定給水装置工事事業者が発行した「修繕完了証明書」（修繕前後のカラー写真添付必須）\n"
        "・修繕工事費用の領収書控または請求書写し\n"
        "書類スキャンデータをシステムメニュー「添付書類管理」より調定番号に紐付けてアップロードし、課長決裁へ回付する。"
    )

    doc.save(output_path)
    print(f"Created: {output_path}")


def create_document_2(output_path: Path):
    doc = Document()
    doc.add_heading("水道料金事務マニュアル：異動・開閉栓処理編", level=0)

    # 第1章
    doc.add_heading("第1章 開栓・閉栓受付基準", level=1)

    doc.add_heading("1.1 開栓・閉栓の受付期日", level=2)
    doc.add_paragraph(
        "水道の使用開始（開栓）および使用中止（閉栓）の受付期日は、作業希望日の「3営業日前」までを原則とする。\n"
        "受付チャネルは、自治体オンライン電子申請窓口、局代表電話コールセンター、および庁舎お客様総合窓口とする。\n"
        "※当日受付の緊急開栓については、転居当日の特別な事情がある場合に限り、当日の現地作業班のスケジュールを確認の上、例外的に受け付けることができる。"
    )

    doc.add_heading("1.2 名義変更の手続き基準", level=2)
    doc.add_paragraph(
        "使用者の名義変更は、「売買・賃貸借に伴う新旧交代」と「世帯主死亡・婚姻等に伴う承継」で取扱いが異なる。\n"
        "1. 承継手続き：親族間の相続等による承継の場合は、届出書の提出により従前の納付義務および給水契約上の地位がそのまま引き継がれる。\n"
        "2. 一般の変更：前使用者が退去し新使用者が入居する場合は、前使用者の閉栓（精算）と新使用者の新規開栓の双方の届出を必要とする。\n"
        "前使用者の未納料金がある場合、新使用者へ未納分を請求することは法的にできないため、前使用者宛ての転居先督促処理へ回すこと。"
    )

    doc.add_heading("1.3 開栓手数料ルール", level=2)
    doc.add_paragraph(
        "給水条例第15条に基づき、水道を開栓する際は「開栓事務手数料」（1件あたり1,000円、非課税）を徴収する。\n"
        "手数料は開栓作業完了後、初回検針時の水道料金請求書に合算して請求する。\n"
        "【特例免除規定】\n"
        "生活保護受給世帯、公営住宅の一括入退去、および火災等の被災による仮住まい開栓の場合は、減免申請書の提出に基づき開栓手数料を全額免除する。"
    )

    # 第2章
    doc.add_heading("第2章 端末操作手順", level=1)

    doc.add_heading("2.1 システムメニュー「水栓管理」（画面ID: WTR-001）での異動フラグ更新手順", level=2)
    doc.add_paragraph(
        "1. 水道業務基幹ポータル画面から「水栓管理」（画面ID: WTR-001）を起動する。\n"
        "2. 水栓番号入力欄に10桁の水栓番号を入力し、「照会」ボタンを押下して水栓台帳詳細画面を表示する。\n"
        "3. 画面中央の「異動処理」タブを選択する。\n"
        "4. 異動種別を選択：開栓時は「異動フラグ：1（開栓）」、閉栓時は「異動フラグ：2（閉栓）」を選択する。\n"
        "5. 開栓（閉栓）希望日、新使用者氏名・連絡先電話番号、請求先住所を入力する。\n"
        "6. 入力内容のバリデーションチェックを実行後、「登録確定」ボタンを押下して水栓マスタを更新する。"
    )

    doc.add_heading("2.2 検針ハンディ端末への連携フロー", level=2)
    doc.add_paragraph(
        "水栓管理画面で登録された異動データは、巡回検針員が所持する検針ハンディターミナル端末へ自動バッチ連携される。\n"
        "・定期連携バッチ：毎日「17:00」（翌日作業分）および「翌朝08:30」（当日緊急分）の1日2回自動実行。\n"
        "・即時連携手順：緊急開栓等で即時反映が必要な場合は、画面ID: WTR-001 上の「ハンディ緊急即時送信」ボタンを押下する。\n"
        "送信完了後、通信ステータス欄に「HND-OK-01（正常連携完了）」が表示されたことを必ず目視確認すること。"
    )

    doc.save(output_path)
    print(f"Created: {output_path}")


def create_document_3(output_path: Path):
    doc = Document()
    doc.add_heading("水道料金事務マニュアル：検針異常・メーター管理編", level=0)

    # 第1章
    doc.add_heading("第1章 検針値の急増・急減アラート対応", level=1)

    doc.add_heading("1.1 前年同期比200%超時の異常値判定基準", level=2)
    doc.add_paragraph(
        "定期検針において入力されたメーター指示数に基づき、使用水量が以下の基準に該当する場合、システムは「検針異常アラート」を発行する。\n\n"
        "【異常値判定基準】\n"
        "1. 水量急増アラート：当期使用水量が「前年同期実績の200%以上」かつ「差分水量が30立方メートル以上」の場合。\n"
        "   （前年実績がない新規水栓の場合は、直前検針実績の250%以上）\n"
        "2. 水量急減アラート：前回検針と比較して使用水量が「50%以下」に激減しているか、または「指示数差0（使用量ゼロ）」の場合。\n"
        "3. マイナス指示数：当期指示数が前回指示数を下回っている場合（メーター逆回転または誤読の疑い）。"
    )

    doc.add_heading("1.2 現場調査票の発行要件", level=2)
    doc.add_paragraph(
        "水量急増アラートが発生した水栓については、調定確定を自動保留とし、直ちに現地確認を実施する。\n"
        "【現場調査票の自動発行】\n"
        "・前年同期比200%超のアラート水栓は、翌朝バッチにて「現地調査指示票（メーター異常・漏水精査用）」が自動印刷・起票される。\n"
        "【調査員の確認項目および派遣要件】\n"
        "・調査員は指示票発行後「2営業日以内」に対象現地へ赴き、以下の項目を点検・確認する：\n"
        "  ① パイロットマークの回転状態（蛇口を全て閉めた状態での回転有無＝地下漏水の可能性確認）\n"
        "  ② メーター器号・口径・現在指針の再確認（検針員の誤読チェック）\n"
        "  ③ 居住者へのヒアリング（家族増員、リフォーム、庭木散水、プール使用等の要因確認）"
    )

    # 第2章
    doc.add_heading("第2章 端末操作手順", level=1)

    doc.add_heading("2.1 システムメニュー「検針データ精査」（画面ID: WTR-MTR-205）の操作", level=2)
    doc.add_paragraph(
        "1. システムメニューから「検針管理業務」→「検針データ精査」（画面ID: WTR-MTR-205）を起動する。\n"
        "2. 検索条件エリアにて、対象の「検針区（ブロック番号）」「検針年月」を指定し、「異常データ抽出」をクリックする。\n"
        "3. エラー一覧グリッドに、アラート種別ごとに色分けされた検針データ行が表示される。\n"
        "4. 対象の明細行をダブルクリックし、検針精査詳細画面を展開する。"
    )

    doc.add_heading("2.2 エラーコード「E-402」の解除および再検針指示フロー", level=2)
    doc.add_paragraph(
        "前年同期比200%超の水量急増水栓には、エラーコード「E-402（水量急増・漏水疑い）」が付与されている。\n\n"
        "【調査結果が正常使用（家族増等）または漏水確定の場合の解除手順】\n"
        "1. 精査詳細画面の「精査事由区分」より該当理由（01:家族増員、02:散水・工事使用、03:漏水認定・減免へ移行）を選択する。\n"
        "2. 調査員が持ち帰った現場調査票の受付番号を入力する。\n"
        "3. 「エラー解除フラグ」にチェックを入れ、「精査完了（調定承認）」ボタンを押下する。\n\n"
        "【検針員の誤読またはメーター故障疑いによる再検針指示手順】\n"
        "1. 画面右上の「再検針指示」ボタンをクリックする。\n"
        "2. 再検針理由（04:指針誤読疑い、05:メーター不回転）を入力する。\n"
        "3. 「ハンディ再送信」を実行すると、該当ブロックの検針ハンディ端末に再検針タスクが即時割り当てられる。"
    )

    doc.save(output_path)
    print(f"Created: {output_path}")


def main():
    base_dir = Path(__file__).parent
    data_dir = base_dir / "data"
    data_dir.mkdir(parents=True, exist_ok=True)
    print(f"Ensured directory exists: {data_dir}")

    create_document_1(data_dir / "01_漏水減免・更正処理編.docx")
    create_document_2(data_dir / "02_異動・開閉栓処理編.docx")
    create_document_3(data_dir / "03_検針異常・メーター管理編.docx")
    print("All dummy documents generated successfully.")


if __name__ == "__main__":
    main()
